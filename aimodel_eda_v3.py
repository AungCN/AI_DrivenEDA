# AutoML PRO App (Streamlit)

import streamlit as st
import pandas as pd
import numpy as np
import time
from sklearn.model_selection import train_test_split, GridSearchCV
from sklearn.preprocessing import LabelEncoder
from sklearn.metrics import accuracy_score, r2_score, confusion_matrix, ConfusionMatrixDisplay
from sklearn.linear_model import LogisticRegression, LinearRegression
from sklearn.ensemble import RandomForestClassifier, RandomForestRegressor
from sklearn.svm import SVC, SVR
from sklearn.neighbors import KNeighborsClassifier, KNeighborsRegressor
from sklearn.tree import DecisionTreeClassifier, DecisionTreeRegressor
import matplotlib.pyplot as plt
import seaborn as sns

# Optional (advanced models)
try:
    from xgboost import XGBClassifier, XGBRegressor
    from lightgbm import LGBMClassifier, LGBMRegressor
    from catboost import CatBoostClassifier, CatBoostRegressor
    advanced_models_available = True
except ImportError:
    advanced_models_available = False

# Set page config
st.set_page_config(page_title="🔮 AutoML & EDA Pro App", layout="wide")

# Title
st.title("🔮 AutoML & EDA Pro App")
st.caption("Upload your dataset and let AI do the work!")

# Upload Dataset
st.sidebar.header("Upload Dataset")
file = st.sidebar.file_uploader("Upload your CSV", type=["csv"])

if file is not None:
    df = pd.read_csv(file)
    st.subheader("📄 Raw Data")
    st.dataframe(df)

    # EDA
    if st.checkbox("Show EDA Summary"):
        st.subheader("📊 EDA Summary")
        st.write(df.describe())
        st.write(df.info())

    # Feature Selection
    st.sidebar.header("Feature Selection")
    target = st.sidebar.selectbox("Select Target Variable", df.columns)

    if target:

        # Encode categorical variables
        le = LabelEncoder()
        for col in df.select_dtypes(include=["object"]).columns:
            df[col] = le.fit_transform(df[col].astype(str))

        X = df.drop(target, axis=1)
        y = df[target]

        # Train-test Split
        test_size = st.sidebar.slider("Test Size (%)", 10, 50, 20)
        X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=test_size/100, random_state=42)

        # Task type
        task_type = "classification" if df[target].nunique() <= 10 else "regression"

        st.sidebar.header("Model Options")
        hyperparameter_tuning = st.sidebar.checkbox("Enable Hyperparameter Tuning", value=False)

        models = {}

        if task_type == "classification":
            models = {
                "Logistic Regression": LogisticRegression(max_iter=1000),
                "Random Forest Classifier": RandomForestClassifier(),
                "SVM Classifier": SVC(),
                "KNN Classifier": KNeighborsClassifier(),
                "Decision Tree Classifier": DecisionTreeClassifier()
            }
            if advanced_models_available:
                models.update({
                    "XGBoost Classifier": XGBClassifier(),
                    "LightGBM Classifier": LGBMClassifier(),
                    "CatBoost Classifier": CatBoostClassifier(verbose=0)
                })

        else:
            models = {
                "Linear Regression": LinearRegression(),
                "Random Forest Regressor": RandomForestRegressor(),
                "SVR Regressor": SVR(),
                "KNN Regressor": KNeighborsRegressor(),
                "Decision Tree Regressor": DecisionTreeRegressor()
            }
            if advanced_models_available:
                models.update({
                    "XGBoost Regressor": XGBRegressor(),
                    "LightGBM Regressor": LGBMRegressor(),
                    "CatBoost Regressor": CatBoostRegressor(verbose=0)
                })

        leaderboard = []

        st.subheader("🏆 Model Leaderboard")

        for model_name, model in models.items():
            result = {"Model": model_name}

            try:
                start_time = time.time()

                if hyperparameter_tuning:
                    param_grid = {}
                    if isinstance(model, RandomForestClassifier) or isinstance(model, RandomForestRegressor):
                        param_grid = {'n_estimators': [50, 100]}
                    if param_grid:
                        grid = GridSearchCV(model, param_grid, cv=3)
                        grid.fit(X_train, y_train)
                        best_model = grid.best_estimator_
                        result["Best Parameters"] = grid.best_params_
                    else:
                        best_model = model
                        best_model.fit(X_train, y_train)
                        result["Best Parameters"] = "Default"
                else:
                    best_model = model
                    best_model.fit(X_train, y_train)
                    result["Best Parameters"] = "Default"

                preds = best_model.predict(X_test)

                if task_type == "classification":
                    score = accuracy_score(y_test, preds)
                else:
                    score = r2_score(y_test, preds)

                result["Score"] = score
                result["Training Time"] = round(time.time() - start_time, 2)

            except Exception as e:
                st.error(f"Training failed for {model_name}: {e}")
                result["Score"] = 0
                result["Training Time"] = 0
                result["Best Parameters"] = "Error"

            leaderboard.append(result)

        leaderboard_df = pd.DataFrame(leaderboard)

        if "Score" in leaderboard_df.columns:
            leaderboard_df = leaderboard_df.sort_values(by="Score", ascending=False)

        st.dataframe(leaderboard_df)

        # Download Leaderboard
        csv = leaderboard_df.to_csv(index=False).encode('utf-8')
        st.download_button("⬇️ Download Leaderboard", csv, "leaderboard.csv")

        # Visualization
        st.subheader("📈 Model Comparison")

        fig, ax = plt.subplots(figsize=(10, 6))
        sns.barplot(data=leaderboard_df, x="Score", y="Model", ax=ax, palette="viridis")
        st.pyplot(fig)

        # Confusion Matrix for Best Model
        best_model_name = leaderboard_df.iloc[0]["Model"]
        best_model = models[best_model_name]
        best_model.fit(X_train, y_train)
        preds = best_model.predict(X_test)

        if task_type == "classification":
            st.subheader(f"🧩 Confusion Matrix for {best_model_name}")
            cm = confusion_matrix(y_test, preds)
            disp = ConfusionMatrixDisplay(confusion_matrix=cm)
            disp.plot(cmap="Blues")
            st.pyplot(plt)

        # Feature Importances for Tree-based Models
        if hasattr(best_model, "feature_importances_"):
            st.subheader(f"🌟 Feature Importances for {best_model_name}")
            feature_importance_df = pd.DataFrame({
                "Feature": X.columns,
                "Importance": best_model.feature_importances_
            }).sort_values(by="Importance", ascending=False)

            fig2, ax2 = plt.subplots(figsize=(10, 6))
            sns.barplot(data=feature_importance_df, x="Importance", y="Feature", ax=ax2, palette="coolwarm")
            st.pyplot(fig2)

else:
    st.info("👈 Please upload a CSV file to start!")


