# 🚀 Must be the first line
import streamlit as st
st.set_page_config(page_title="AI-Driven EDA + AutoML", layout="wide")

# Core Libraries
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

# ML Models
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import LabelEncoder, StandardScaler
from sklearn.linear_model import LogisticRegression, LinearRegression
from sklearn.tree import DecisionTreeClassifier, DecisionTreeRegressor
from sklearn.ensemble import RandomForestClassifier, RandomForestRegressor
from sklearn.neighbors import KNeighborsClassifier
from sklearn.metrics import accuracy_score, mean_squared_error, classification_report, r2_score

# Try importing XGBoost (optional)
try:
    from xgboost import XGBClassifier, XGBRegressor
    xgb_installed = True
except:
    xgb_installed = False

# --------------------------------------------
# 🎨 App Title
st.title("🤖 AI-Driven EDA + AutoML App")
st.markdown("Upload your dataset, explore EDA, and train multiple ML models automatically!")

# --------------------------------------------
# 📤 Upload File
uploaded_file = st.file_uploader("Upload CSV File", type=["csv"])
if uploaded_file:
    df = pd.read_csv(uploaded_file)

    # ----------------------------------------
    # 📊 EDA Section
    st.subheader("📊 Exploratory Data Analysis")
    st.write(df.head())

    if st.checkbox("Show Shape"):
        st.write(df.shape)

    if st.checkbox("Show Summary Stats"):
        st.write(df.describe())

    if st.checkbox("Show Missing Values"):
        st.write(df.isnull().sum())

    if st.checkbox("Correlation Heatmap (numerical only)"):
        corr = df.select_dtypes(include=np.number).corr()
        plt.figure(figsize=(10, 8))
        sns.heatmap(corr, annot=True, cmap="coolwarm")
        st.pyplot(plt)

    # ----------------------------------------
    # 🏷️ Target Variable
    st.sidebar.header("🏷️ Define Target Variable")
    target_col = st.sidebar.selectbox("Select Target Column", df.columns)

    # Problem Type
    problem_type = st.sidebar.radio("Problem Type", ("Classification", "Regression"))

    # ----------------------------------------
    # 🧹 Preprocessing
    X = df.drop(columns=[target_col])
    y = df[target_col]

    # Encoding categorical features
    for col in X.select_dtypes(include="object").columns:
        X[col] = LabelEncoder().fit_transform(X[col].astype(str))

    if y.dtype == 'object':
        y = LabelEncoder().fit_transform(y.astype(str))

    # Scaling features
    scaler = StandardScaler()
    X_scaled = scaler.fit_transform(X)

    X_train, X_test, y_train, y_test = train_test_split(X_scaled, y, test_size=0.2, random_state=42)

    # ----------------------------------------
    # 🧠 Model Selection
    st.sidebar.header("⚙️ Model Selection")

    available_models = {
        'Logistic Regression': LogisticRegression(),
        'K-Nearest Neighbors': KNeighborsClassifier(),
        'Decision Tree': DecisionTreeClassifier(),
        'Random Forest': RandomForestClassifier()
    }

    if xgb_installed:
        available_models['XGBoost Classifier'] = XGBClassifier(use_label_encoder=False, eval_metric='logloss')

    if problem_type == "Regression":
        available_models = {
            'Linear Regression': LinearRegression(),
            'Decision Tree Regressor': DecisionTreeRegressor(),
            'Random Forest Regressor': RandomForestRegressor()
        }
        if xgb_installed:
            available_models['XGBoost Regressor'] = XGBRegressor()

    # Auto Recommendation
    num_samples = X.shape[0]
    num_features = X.shape[1]
    num_classes = len(np.unique(y))

    auto_recommend = []
    if problem_type == "Classification":
        if num_classes == 2:
            auto_recommend = ['Logistic Regression', 'Random Forest', 'XGBoost Classifier']
        else:
            auto_recommend = ['Random Forest', 'XGBoost Classifier', 'K-Nearest Neighbors']
    else:
        if num_features > 20:
            auto_recommend = ['Random Forest Regressor', 'XGBoost Regressor']
        else:
            auto_recommend = ['Linear Regression', 'Random Forest Regressor']

    st.sidebar.markdown(f"🧠 **Recommended Models:** `{', '.join(auto_recommend)}`")

    # Select Models
    train_all = st.sidebar.checkbox("🚀 Train All Models", value=True)

    selected_models = []
    for model_name in available_models.keys():
        if train_all or st.sidebar.checkbox(model_name, value=(model_name in auto_recommend)):
            selected_models.append(model_name)

    # ----------------------------------------
    # 🏋️‍♂️ Training
    if st.sidebar.button("Train Selected Models"):
        leaderboard = []

        for model_name in selected_models:
            model = available_models[model_name]
            model.fit(X_train, y_train)
            preds = model.predict(X_test)

            if problem_type == "Classification":
                score = accuracy_score(y_test, preds)
            else:
                score = np.sqrt(mean_squared_error(y_test, preds))  # RMSE

            leaderboard.append({
                "Model": model_name,
                "Score": score
            })

        # Display Leaderboard
        leaderboard_df = pd.DataFrame(leaderboard).sort_values(by="Score", ascending=(problem_type=="Regression"))
        st.subheader("🏆 Model Leaderboard")
        st.dataframe(leaderboard_df)

        # 🎯 Best Model Highlight
        best_model = leaderboard_df.iloc[0]
        st.success(f"🎯 Best Model: **{best_model['Model']}** with Score: **{best_model['Score']:.4f}**")

