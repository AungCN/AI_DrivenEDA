# --------------- Imports ---------------
import streamlit as st
import pandas as pd
import numpy as np
import seaborn as sns
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.model_selection import train_test_split, GridSearchCV
from sklearn.preprocessing import LabelEncoder, StandardScaler
from sklearn.metrics import accuracy_score, mean_squared_error, r2_score
from sklearn.ensemble import RandomForestClassifier, RandomForestRegressor
from sklearn.linear_model import LogisticRegression, LinearRegression
from sklearn.svm import SVC, SVR
from sklearn.neighbors import KNeighborsClassifier, KNeighborsRegressor
from sklearn.tree import DecisionTreeClassifier, DecisionTreeRegressor
from sklearn.naive_bayes import GaussianNB

import joblib
import os

import tensorflow as tf
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Dense


## --------------- Streamlit Page Config ---------------
st.set_page_config(page_title="🛠️ PRO MAX: AutoML & Deep Learning", layout="wide")

# --------------- Sidebar: Theme Switcher ---------------
theme = st.sidebar.radio("Theme Mode", ["Light", "Dark"])

if theme == "Dark":
    st.markdown("""
    <style>
    body {
        background-color: #0e1117;
        color: white;
    }
    </style>
    """, unsafe_allow_html=True)

# --------------- Title ---------------
st.title("🛠️ PRO MAX: AutoML + Deep Learning App 🚀")

# --------------- Sidebar: Upload Data ---------------
st.sidebar.header("📂 Upload Dataset")
uploaded_file = st.sidebar.file_uploader("Upload your CSV file", type=["csv"])

if uploaded_file is not None:
    data = pd.read_csv(uploaded_file)
    st.subheader("🔎 Dataset Preview")
    st.write(data.head())

    # EDA Section
    st.subheader("📊 Exploratory Data Analysis")
    st.write("Dataset Shape:", data.shape)
    st.write(data.describe())
    st.write("Missing Values:", data.isnull().sum())

    st.subheader("Correlation Heatmap (Numeric Only)")
    fig, ax = plt.subplots(figsize=(10,8))
    sns.heatmap(data.corr(numeric_only=True), annot=True, cmap='coolwarm')
    st.pyplot(fig)

    # Sidebar: Features and Target
    st.sidebar.header("🎯 Feature & Target Selection")
    target = st.sidebar.selectbox("Select your target column", data.columns)
    features = st.sidebar.multiselect("Select feature columns", [col for col in data.columns if col != target])

    if features:
        X = data[features]
        y = data[target]

        for col in X.select_dtypes(include=['object']).columns:
            lbl = LabelEncoder()
            X[col] = lbl.fit_transform(X[col].astype(str))

        if y.dtype == 'object':
            lbl = LabelEncoder()
            y = lbl.fit_transform(y.astype(str))

        test_size = st.sidebar.slider("Test size (%)", 10, 50, 20)
        X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=test_size/100, random_state=42)

        # Sidebar: Model Options
        st.sidebar.header("🤖 Model Selection")

        model_type = st.sidebar.selectbox("Task Type", ["Classification", "Regression", "Neural Network"])

        best_model = None
        results = {}

        if model_type == "Classification":
            models = {
                "Random Forest": RandomForestClassifier(),
                "Logistic Regression": LogisticRegression(max_iter=1000),
                "Decision Tree": DecisionTreeClassifier(),
                "KNN": KNeighborsClassifier(),
                "Naive Bayes": GaussianNB(),
                "SVM": SVC()
            }
        elif model_type == "Regression":
            models = {
                "Random Forest": RandomForestRegressor(),
                "Linear Regression": LinearRegression(),
                "Decision Tree": DecisionTreeRegressor(),
                "KNN": KNeighborsRegressor(),
                "SVR": SVR()
            }
        else:
            models = {"Neural Network": None}

        selected_models = st.sidebar.multiselect("Choose Models to Train", list(models.keys()), default=list(models.keys())[:2])

        # Train and Evaluate
        st.subheader("🏃 Training Results")

        learning_curves = {}

        for model_name in selected_models:
            if model_type == "Neural Network" and model_name == "Neural Network":
                scaler = StandardScaler()
                X_train_scaled = scaler.fit_transform(X_train)
                X_test_scaled = scaler.transform(X_test)

                model = Sequential([
                    Dense(64, activation='relu', input_dim=X_train.shape[1]),
                    Dense(32, activation='relu'),
                    Dense(1, activation='sigmoid' if len(np.unique(y_train)) == 2 else 'linear')
                ])
                model.compile(optimizer='adam', loss='binary_crossentropy' if len(np.unique(y_train)) == 2 else 'mse')

                history = model.fit(X_train_scaled, y_train, validation_data=(X_test_scaled, y_test),
                                    epochs=50, batch_size=32, verbose=0)

                preds = model.predict(X_test_scaled)
                preds = np.where(preds > 0.5, 1, 0) if len(np.unique(y_train)) == 2 else preds

                # Save learning curve
                learning_curves[model_name] = history
            else:
                model = models[model_name]
                model.fit(X_train, y_train)
                preds = model.predict(X_test)

            if model_type == "Classification":
                acc = accuracy_score(y_test, preds)
                results[model_name] = acc
            else:
                rmse = np.sqrt(mean_squared_error(y_test, preds))
                results[model_name] = rmse

        # Show results
        st.write(results)

        # Best model
        if model_type == "Classification":
            best_model = max(results, key=results.get)
            st.success(f"🥇 Best Model: {best_model} with Accuracy {results[best_model]:.4f}")
        else:
            best_model = min(results, key=results.get)
            st.success(f"🥇 Best Model: {best_model} with RMSE {results[best_model]:.4f}")

        # Feature Importance Plot
        if st.checkbox("🎯 Show Feature Importances (Tree models only)"):
            if best_model in ["Random Forest", "Decision Tree"]:
                model = models[best_model]
                model.fit(X_train, y_train)
                importances = model.feature_importances_
                feat_imp = pd.Series(importances, index=features).sort_values(ascending=False)

                st.bar_chart(feat_imp)

        # Save model
        if st.button("💾 Save Best Model"):
            os.makedirs("saved_models", exist_ok=True)
            filename = f"saved_models/{best_model.replace(' ', '_').lower()}_model.pkl"
            joblib.dump(models[best_model], filename)
            st.success(f"Model saved at {filename}")

        # Download Results as CSV
        results_df = pd.DataFrame(list(results.items()), columns=["Model", "Score"])
        csv = results_df.to_csv(index=False).encode('utf-8')

        st.download_button(
            label="📄 Download Results Report",
            data=csv,
            file_name='model_performance_report.csv',
            mime='text/csv',
        )

        # Plot learning curve if neural network
        if learning_curves:
            st.subheader("📈 Neural Network Learning Curve")
            for model_name, history in learning_curves.items():
                fig, ax = plt.subplots()
                ax.plot(history.history['loss'], label='Training Loss')
                ax.plot(history.history['val_loss'], label='Validation Loss')
                ax.set_title(f'{model_name} - Learning Curve')
                ax.set_xlabel('Epochs')
                ax.set_ylabel('Loss')
                ax.legend()
                st.pyplot(fig)

    else:
        st.warning("👈 Select Features and Target to continue.")

else:
    st.info("👈 Upload a CSV to start.")

